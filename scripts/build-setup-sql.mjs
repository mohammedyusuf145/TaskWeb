// Concatenates every migration, in order, into supabase/setup.sql: one file to paste into
// Supabase → SQL Editor → Run. Every migration is idempotent, so running it again is safe.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'supabase/migrations';
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const parts = files.map((f) => `-- ────────────────────────────────────────────────────────────────────────────\n-- ${f}\n-- ────────────────────────────────────────────────────────────────────────────\n\n${readFileSync(join(dir, f), 'utf8').trim()}\n`);
const header = `-- Mizan database setup (generated by scripts/build-setup-sql.mjs; do not edit by hand).
-- Paste this whole file into Supabase → SQL Editor → New query → Run.
-- Safe to run more than once: every statement is idempotent.

`;
writeFileSync('supabase/setup.sql', header + parts.join('\n'));
console.log(`supabase/setup.sql: ${files.length} migrations`);
